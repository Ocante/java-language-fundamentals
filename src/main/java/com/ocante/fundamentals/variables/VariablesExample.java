package com.ocante.fundamentals.variables;

public class VariablesExample {

    public static void main(String[] args) {
        String employeeName = "Carlos Mendes";
        int employeeAge = 35;
        double monthlySalary = 7200.50;
        boolean isActive = false;
        char employeeCategory = 'B';

        System.out.println("EMPLOYEE INFORMATION");
        System.out.println("--------------------");

        System.out.println("Name: " + employeeName);
        System.out.println("Age: " + employeeAge);
        System.out.println("salary: " + monthlySalary);
        System.out.println("Active: " + isActive);
        System.out.println("Category: " + employeeCategory);
    }
}
